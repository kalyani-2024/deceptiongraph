"""Research commands: larger networks, sensitivity, smarter attackers.

    dgraph generate    -n 200 -o data/generated/net200.yaml
    dgraph adversary   data/networks/campus.yaml -t 300
    dgraph sensitivity data/networks/campus.yaml -t 150
    dgraph scale       --sizes 50,100,200 -t 100
"""

from __future__ import annotations

import json
import time
from pathlib import Path

import typer
import yaml
from rich.console import Console
from rich.table import Table

console = Console()


def _write_json(out: Path | None, payload) -> None:
    if out is None:
        return
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(payload, indent=2, default=str), encoding="utf-8")
    console.print(f"[green]Wrote[/] {out}")


def _network(path: Path):
    from ..graph.loader import load_network

    try:
        return load_network(path)
    except (FileNotFoundError, ValueError) as exc:
        console.print(f"[bold red]error:[/] {exc}")
        raise typer.Exit(code=1) from exc


def generate(
    hosts: int = typer.Option(100, "--hosts", "-n", help="Roughly how many hosts."),
    seed: int = typer.Option(0, "--seed"),
    out: Path = typer.Option(Path("network.yaml"), "--out", "-o"),
) -> None:
    """Generate an enterprise-shaped network of any size (tiers, CVEs, credentials)."""
    from ..graph.generator import generate_network
    from ..graph.loader import build_model

    try:
        raw = generate_network(hosts, seed=seed)
    except ValueError as exc:
        console.print(f"[bold red]error:[/] {exc}")
        raise typer.Exit(code=1) from exc
    summary = build_model(raw).summary()
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(f"# Generated by `dgraph generate -n {hosts} --seed {seed}`. Synthetic.\n"
                   + yaml.safe_dump(raw, sort_keys=False), encoding="utf-8")
    console.print(f"[green]Wrote[/] {out}: {summary['hosts']} hosts, "
                  f"{summary['vulnerabilities']} CVEs, {summary['credentials']} credentials, "
                  f"{summary['connections']} connections, "
                  f"crown jewels {', '.join(summary['crown_jewels'])}")


def adversary(
    network: Path = typer.Argument(..., help="Network definition YAML."),
    budget: int = typer.Option(3, "--budget", "-b"),
    trials: int = typer.Option(200, "--trials", "-t"),
    seed: int = typer.Option(2024, "--seed"),
    out: Path = typer.Option(None, "--out", "-o"),
) -> None:
    """Detection against naive, cautious and learning attackers, per strategy."""
    from ..experiments.adversaries import compare_adversaries

    model = _network(network)
    with console.status(f"Three experiments of {trials} campaigns per strategy..."):
        rows = compare_adversaries(model, budget=budget, trials=trials, seed=seed)

    table = Table(title=f"{model.name}: detection by attacker model (budget {budget}, "
                  f"{trials} campaigns)", header_style="bold cyan")
    for column in ("Strategy", "Naive", "Cautious", "Learning", "Learning: first 1/3",
                   "last 1/3", "Kept", "Spotted/campaign"):
        table.add_column(column, justify="left" if column == "Strategy" else "right")
    for r in rows:
        table.add_row(r.strategy, f"{r.naive:.2f}", f"{r.cautious:.2f}", f"{r.learning:.2f}",
                      f"{r.learning_early:.2f}", f"{r.learning_late:.2f}", f"{r.retained:.0%}",
                      f"{r.spotted_per_campaign:.2f}")
    console.print(table)
    console.print("[dim]Naive is the old upper bound. Cautious spots unconvincing decoys; "
                  "learning also remembers them between campaigns. 'Kept' = learning / naive.[/]")
    _write_json(out, [r.as_dict() for r in rows])


def sensitivity(
    network: Path = typer.Argument(..., help="Network definition YAML."),
    budget: int = typer.Option(3, "--budget", "-b"),
    trials: int = typer.Option(100, "--trials", "-t"),
    seed: int = typer.Option(2024, "--seed"),
    parameters: str = typer.Option(None, "--parameters", "-p",
                                   help="Comma-separated (default: all)."),
    adversary_name: str = typer.Option("naive", "--adversary", "-a",
                                       help="naive | cautious | learning"),
    out: Path = typer.Option(None, "--out", "-o"),
) -> None:
    """Vary each guessed probability by 0.5x-1.5x: does the winning strategy change?"""
    from ..experiments.sensitivity import run_sensitivity

    model = _network(network)
    chosen = tuple(p.strip() for p in parameters.split(",")) if parameters else None
    started = time.perf_counter()
    try:
        with console.status("Rerunning the experiment for every parameter value..."):
            results = run_sensitivity(model, parameters=chosen, budget=budget, trials=trials,
                                      seed=seed, adversary=adversary_name)
    except ValueError as exc:
        console.print(f"[bold red]error:[/] {exc}")
        raise typer.Exit(code=1) from exc

    table = Table(title=f"{model.name}: sensitivity (budget {budget}, {trials} trials per value)",
                  header_style="bold cyan")
    for column in ("Parameter", "Values", "Winner", "Stable", "Min tau", "Widest swing"):
        table.add_column(column)
    for r in results:
        widest = max(r.detection, key=r.spread)
        table.add_row(
            r.parameter, ", ".join(f"{v:g}" for v in r.values),
            " / ".join(dict.fromkeys(r.winners)),
            "[green]yes[/]" if r.winner_stable else "[red]no[/]",
            f"{r.min_tau:.2f}", f"{widest} {r.spread(widest):.2f}",
        )
    console.print(table)
    console.print(f"[dim]One parameter at a time, others at default, identical seeds. Tau 1 = "
                  f"same strategy ranking as the default; -1 = reversed. "
                  f"{time.perf_counter() - started:.0f}s.[/]")
    _write_json(out, [r.as_dict() for r in results])


def scale(
    sizes: str = typer.Option("50,100,200", "--sizes", help="Comma-separated host counts."),
    budget: int = typer.Option(5, "--budget", "-b"),
    trials: int = typer.Option(100, "--trials", "-t"),
    seed: int = typer.Option(1, "--seed"),
    adversary_name: str = typer.Option("naive", "--adversary", "-a"),
    out: Path = typer.Option(None, "--out", "-o"),
) -> None:
    """Run the placement experiment on generated networks of growing size."""
    from ..experiments.runner import ExperimentRunner
    from ..facade import SecurityFacade
    from ..graph.generator import generate_network
    from ..graph.loader import build_model

    try:
        counts = [int(s) for s in sizes.split(",") if s.strip()]
    except ValueError as exc:
        console.print("[bold red]error:[/] --sizes must be integers")
        raise typer.Exit(code=1) from exc

    table = Table(title=f"Scaling: budget {budget}, {trials} trials, adversary {adversary_name}",
                  header_style="bold cyan")
    for column in ("Hosts", "Analysis s", "Experiment s", "Winner", "Detection by strategy"):
        table.add_column(column)
    payload = []
    for n in counts:
        model = build_model(generate_network(n, seed=seed))
        t0 = time.perf_counter()
        SecurityFacade(model).analyse_network()
        analysis_s = time.perf_counter() - t0
        t0 = time.perf_counter()
        with console.status(f"{n} hosts..."):
            report = ExperimentRunner(model, trials=trials, seed=seed,
                                      adversary=adversary_name).run(budget=budget)
        experiment_s = time.perf_counter() - t0
        ranked = report.ranked
        table.add_row(str(len(model.hosts)), f"{analysis_s:.2f}", f"{experiment_s:.0f}",
                      ranked[0].label,
                      "  ".join(f"{a.label} {a.metrics.detection_rate:.2f}" for a in ranked))
        payload.append({"hosts": len(model.hosts), "analysis_seconds": round(analysis_s, 3),
                        "experiment_seconds": round(experiment_s, 1), **report.as_dict()})
    console.print(table)
    _write_json(out, payload)
